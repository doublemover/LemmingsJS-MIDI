import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';

export function createSpectrumSource() {
  const size = 2048, levels = [1, 2, 4, 8, 16], frames = [], tables = []; let peak = 0;
  const landmarks = [Array.from({ length: 16 }, (_, index) => index ? 0 : 1),
    Array.from({ length: 16 }, (_, index) => index % 2 ? 0 : 1 / (index + 1) ** 1.1),
    Array.from({ length: 16 }, (_, index) => 1 / (index + 1) ** 1.25),
    Array.from({ length: 16 }, (_, index) => index ? (index >= 2 && index <= 5 ? 0.8 : 0.08) / (index + 1) ** 0.5 : 0.7)];
  for (let frame = 0; frame < 16; frame++) {
    const position = frame / 5, first = Math.min(2, Math.floor(position)), blend = position - first;
    const gains = landmarks[first].map((gain, index) => gain + (landmarks[first + 1][index] - gain) * blend); frames.push(...gains);
    for (const count of levels) for (let sample = 0; sample <= size; sample++) {
      let value = 0;
      if (sample && sample !== size) for (let harmonic = 1; harmonic <= count; harmonic++) value += Math.sin(2 * Math.PI * sample / size * harmonic) * gains[harmonic - 1];
      tables.push(value); peak = Math.max(peak, Math.abs(value));
    }
  }
  const normalization = 0.8 / peak, sine = Array.from({ length: size + 1 }, (_, index) => index && index !== size ? Math.sin(2 * Math.PI * index / size) : 0);
  const normalizedTables = tables.map(value => value * normalization), hash = createHash('sha256');
  hash.update(JSON.stringify({ generator: 'spectrum-fourier-16x5x2048-v1', size, levels, frames: 16, normalization })); hash.update('\0');
  for (const values of [frames, sine, normalizedTables]) { const bytes = Buffer.alloc(values.length * 4); values.forEach((value, index) => bytes.writeFloatLE(Math.fround(value), index * 4)); hash.update(bytes); }
  const dataHash = hash.digest('hex');
  const array = (name, values) => {
    const lines = []; for (let index = 0; index < values.length; index += 8) lines.push('  ' + values.slice(index, index + 8).map(value => String(Number(Math.fround(value).toPrecision(9)))).join(', '));
    return 'export const ' + name + ' = Object.freeze([\n' + lines.join(',\n') + '\n]);\n';
  };
  return { source: '// Generated by scripts/build-spectrum-source.mjs. Original phase-aligned Fourier frames.\n' +
    "export const SPECTRUM_GENERATOR = 'spectrum-fourier-16x5x2048-v1';\n" + "export const SPECTRUM_DATA_SHA256 = '" + dataHash + "';\n" + 'export const SPECTRUM_NORMALIZATION = ' + normalization + ';\n' +
    array('SPECTRUM_LEVELS', levels) + array('SPECTRUM_FRAME_GAINS', frames) + array('SPECTRUM_SINE', sine) + array('SPECTRUM_TABLES', normalizedTables),
  samples: tables.length + sine.length + frames.length, qualification: 'authored-source-data-not-render-qualified' };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const name = process.argv.find(value => value.startsWith('--name='))?.slice(7) || 'anonymous';
  if (!/^[a-z0-9_-]{1,32}$/i.test(name)) throw new Error('Invalid authoring agent name.');
  const result = createSpectrumSource(); await writeFile(new URL('../js/app/midi-ui/worklet/SpectrumSourceTables.js', import.meta.url), result.source, 'utf8');
  process.stdout.write(JSON.stringify({ name, samples: result.samples, qualification: result.qualification }) + '\n');
}
