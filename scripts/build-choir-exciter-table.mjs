import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const CHOIR_TABLE_GENERATOR = 'harmonic-table-generator-v1';
export function createChoirExciterSource() {
  const levels = [1, 2, 4, 8, 16, 32, 64, 128], tables = []; let peak = 0;
  for (const count of levels) {
    const values = [];
    for (let index = 0; index <= 2048; index++) {
      const phase = index / 2048 * Math.PI * 2; let value = 0;
      if (index && index !== 2048) for (let harmonic = 1; harmonic <= count; harmonic++) value += Math.sin(harmonic * phase) / harmonic;
      values.push(value); peak = Math.max(peak, Math.abs(value));
    }
    tables.push(values);
  }
  const normalization = 0.9 / peak, values = tables.flatMap(table => table.map(value => String(Number(Math.fround(value * normalization).toPrecision(9))))), lines = [];
  for (let index = 0; index < values.length; index += 8) lines.push('  ' + values.slice(index, index + 8).join(', '));
  const source = '// Generated by scripts/build-choir-exciter-table.mjs (' + CHOIR_TABLE_GENERATOR + ').\n' +
    "export const CHOIR_EXCITER_REVISION = 'harmonic-bank-2048-v2';\n" +
    'export const CHOIR_EXCITER_NORMALIZATION = ' + normalization + ';\n' +
    'export const CHOIR_EXCITER_HARMONICS = Object.freeze([' + levels.join(', ') + ']);\n' +
    'export const CHOIR_EXCITER_TABLE = Object.freeze([\n' + lines.join(',\n') + '\n]);\n';
  return { source, normalization, levels, samples: values.length, qualification: 'authored-table-data-not-render-qualified' };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const name = process.argv.find(value => value.startsWith('--name='))?.slice(7) || 'anonymous';
  if (!/^[a-z0-9_-]{1,32}$/i.test(name)) throw new Error('Invalid authoring agent name.');
  const result = createChoirExciterSource();
  await writeFile(new URL('../js/app/midi-ui/worklet/ChoirExciterTable.js', import.meta.url), result.source, 'utf8');
  process.stdout.write(JSON.stringify({ generator: CHOIR_TABLE_GENERATOR, name, samples: result.samples, levels: result.levels, qualification: result.qualification }) + '\n');
}
