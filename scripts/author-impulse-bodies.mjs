import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { IMPULSE_GENERATOR_REVISION, IMPULSE_SOURCE_SPECS, generateProceduralImpulseSource } from '../js/midi/content/ProceduralImpulseSources.js';

const identities = IMPULSE_SOURCE_SPECS.map(spec => {
  const bytes = generateProceduralImpulseSource(spec.id);
  return { ...spec, generatorRevision: IMPULSE_GENERATOR_REVISION, path: 'impulses/' + spec.id + '.wav', bytes: bytes.byteLength,
    sha256: createHash('sha256').update(bytes).digest('hex'), normalizationMode: 'native-rms', maximumLinearGain: 8,
    attribution: 'Original integer-DDS synthetic reflection body; no recording or hardware emulation. Generator ' + IMPULSE_GENERATOR_REVISION + '; seed ' + spec.seed + '; 32000 Hz PCM16; nine source frames of intentional pre-silence; cubic authored decay and 256-frame edge fades. No measured tail trim or acoustic qualification.',
    licenseId: 'NOASSERTION' };
});
await writeFile(new URL('../js/midi/content/ProceduralImpulseIdentities.js', import.meta.url),
  '// Generated by scripts/author-impulse-bodies.mjs; original source-data identities, no recorded audio.\nexport const PROCEDURAL_IMPULSE_IDENTITIES = Object.freeze(' + JSON.stringify(identities, null, 2) + '.map(entry => Object.freeze(entry)));\n');
