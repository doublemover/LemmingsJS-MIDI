import { sampleReadMaximumL1 } from '../js/app/resources/SampleReadBankComputation.js';
import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { createOwnedSourceBankPlanes } from '../js/app/resources/OwnedSourceBankData.js';

const identities = {};
for (const id of ['choir-v1', 'spectrum-v1', 'grain-window-v1', 'sample-read-v1']) {
  const planes = createOwnedSourceBankPlanes(id), hash = createHash('sha256');
  for (const plane of planes) {
    const encoded = Buffer.alloc(plane.byteLength);
    for (let index = 0; index < plane.length; index++) {
      if (!Number.isFinite(plane[index]) || Math.abs(plane[index]) > 2) throw new Error('Invalid fixed source value.');
      encoded.writeFloatLE(plane[index], index * 4);
    }
    hash.update(encoded);
  }
  identities[id] = { hash: hash.digest('hex'), lengths: planes.map(plane => plane.length), bytes: planes.reduce((total, plane) => total + plane.byteLength, 0), ...(id === 'sample-read-v1' ? { maximumL1: sampleReadMaximumL1(planes[0]) } : {}) };
}
const lines = Object.entries(identities).map(([id, entry]) => `  '${id}': Object.freeze({ hash: '${entry.hash}', lengths: Object.freeze(${JSON.stringify(entry.lengths)}), bytes: ${entry.bytes}${entry.maximumL1 ? ', maximumL1: ' + entry.maximumL1 : ''} })`);
await writeFile(new URL('../js/app/midi-ui/OwnedSourceBankIdentities.js', import.meta.url), '// Generated by scripts/build-owned-source-bank-identities.mjs from original fixed Float32 source data.\nexport const OWNED_SOURCE_BANK_IDENTITIES = Object.freeze({\n' + lines.join(',\n') + '\n});\n');
