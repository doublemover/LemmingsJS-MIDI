import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export function createGrainWindowSource() {
  const values = Array.from({ length: 2049 }, (_, index) => index && index !== 2048 ? Math.fround(0.5 - Math.cos(2 * Math.PI * index / 2048) * 0.5) : 0), lines = [];
  for (let index = 0; index < values.length; index += 8) lines.push('  ' + values.slice(index, index + 8).map(value => String(Number(value.toPrecision(9)))).join(', '));
  return "// Generated by scripts/build-grain-window.mjs.\nexport const GRAIN_WINDOW_REVISION = 'hann-2048-v1';\nexport const GRAIN_WINDOW = Object.freeze([\n" + lines.join(',\n') + '\n]);\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const name = process.argv.find(value => value.startsWith('--name='))?.slice(7) || 'anonymous';
  if (!/^[a-z0-9_-]{1,32}$/i.test(name)) throw new Error('Invalid authoring agent name.');
  await writeFile(new URL('../js/app/midi-ui/worklet/GrainWindow.js', import.meta.url), createGrainWindowSource(), 'utf8');
  process.stdout.write(JSON.stringify({ name, samples: 2049, qualification: 'authored-window-data-not-render-qualified' }) + '\n');
}
