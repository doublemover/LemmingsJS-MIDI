import { expect } from 'chai';
import JZZ from 'jzz';
import installSmf from 'jzz-midi-smf';
import { encodeMidiClipFile, decodeMidiClipFile, MIDI_CLIP_MAX_DELTA } from '../../js/midi/protocol/MidiClipFile.js';
installSmf(JZZ);

export const clipColumns = events => {
  const ticks = new Float64Array(events.length), offsets = new Uint32Array(events.length + 1), words = new Uint32Array(events.reduce((sum, event) => sum + event[1].length, 0));
  let at = 0; events.forEach(([tick, packet], index) => { ticks[index] = tick; words.set(packet, at); at += packet.length; offsets[index + 1] = at; });
  return { ticks, offsets, words };
};
const fast = { yieldControl: async () => {} };
const source = (events = [], extra = {}) => ({ ppq: 960, configurationEndTick: 0, endTick: events.at(-1)?.[0] ?? 0, sequence: clipColumns(events), ...extra });
const eventsOf = columns => Array.from(columns.ticks, (tick, index) => [tick, Array.from(columns.words.subarray(columns.offsets[index], columns.offsets[index + 1]))]);
const wordsOf = message => Array.from({ length: message.length / 4 }, (_, index) => (message[index * 4] * 0x1000000 + message[index * 4 + 1] * 0x10000 + message[index * 4 + 2] * 256 + message[index * 4 + 3]) >>> 0);
const independentEvents = clip => Array.from(clip, message => [message.tt, wordsOf(message)]).filter(([, words]) => words[0] !== 0xf0210000);
const wire = words => {
  const bytes = new Uint8Array(8 + words.length * 4); bytes.set([0x53, 0x4d, 0x46, 0x32, 0x43, 0x4c, 0x49, 0x50]);
  const view = new DataView(bytes.buffer); words.forEach((word, index) => view.setUint32(8 + index * 4, word, false)); return bytes;
};
const rejecting = async (operation, code) => {
  let error; try { await operation(); } catch (caught) { error = caught; }
  expect(error, 'expected refusal ' + code).to.have.property('code', code); return error;
};
const tempo = [0xd0100000, 50000000, 0, 0], meter = [0xd0100001, 0x04021800, 0, 0];
const on = [0x41923c00, 0x12340000], off = [0x41823c00, 0xabcd0000];

describe('bounded standards MIDI Clip files with independent jzz-midi-smf 1.9.9 qualification', () => {
  it('writes the exact minimal big-endian structure with no invented metadata', async () => {
    const { bytes, report } = await encodeMidiClipFile(source(), fast);
    expect(Array.from(bytes)).to.deep.equal(Array.from(wire([0x00400000, 0x003003c0, 0x00400000, 0xf0200000, 0, 0, 0, 0x00400000, 0xf0210000, 0, 0, 0])));
    expect(report).to.include({ bytes: 56, quantization: 'none', setupDisposition: 'data-only-never-submitted' });
    const clip = new JZZ.MIDI.Clip(bytes); expect(clip.validate()).to.equal(undefined); expect(clip.ppqn).to.equal(960); expect(clip.at(-1).tt).to.equal(0);
  });
  it('independently preserves groups, release velocity, per-note expression, equal-time order, tempo and meter', async () => {
    const events = [[0, tempo], [0, meter], [0, on], [0, on], [0, [0x4f963c00, 0x43210000]],
      [120, [0x41623c00, 0x89abcdef]], [120, [0x41023c4a, 0xfedcba98]], [480, [0xd0100000, 66666667, 0, 0]],
      [960, [0xd0100001, 0x03021800, 0, 0]], [1000, off], [1000, off], [1000, [0x4f863c00, 0xffff0000]]];
    const take = source(events, { configuration: clipColumns([[0, tempo], [0, meter], [10, [0x21c20a00]]]), configurationEndTick: 240, endTick: 2880 });
    const first = await encodeMidiClipFile(take, fast), second = await encodeMidiClipFile(take, fast);
    expect(second.bytes).to.deep.equal(first.bytes);
    const independent = new JZZ.MIDI.Clip(first.bytes); expect(independent.validate()).to.equal(undefined);
    expect(independentEvents(independent)).to.deep.equal(events); expect(independent.at(-1).tt).to.equal(2880);
    expect(independent.player().durationMS()).to.be.closeTo(1916.666675, 0.000001);
    expect(Array.from(independent.header, message => [message.tt, wordsOf(message)])).to.deep.equal(eventsOf(take.configuration));
    const parsed = await decodeMidiClipFile(first.bytes, fast);
    expect(parsed).to.include({ ppq: 960, configurationEndTick: 240, endTick: 2880 });
    expect(eventsOf(parsed.sequence)).to.deep.equal(events); expect(eventsOf(parsed.configuration)).to.deep.equal(eventsOf(take.configuration));
    expect((await encodeMidiClipFile(parsed, fast)).bytes).to.deep.equal(first.bytes);
  });
  it('imports files generated by the independent writer, including shared clockstamps', async () => {
    const clip = new JZZ.MIDI.Clip(); clip.ppqn = 65535;
    clip.header.add(0, JZZ.UMP(Array.from(new Uint8Array(wire(tempo).buffer, 8))));
    clip.gr(15).ch(3).umpNoteOn(60, 0xffff).tick(65535).umpNoteOff(60, 0xabcd);
    const parsed = await decodeMidiClipFile(clip.toUint8Array(), fast);
    expect(parsed.ppq).to.equal(65535); expect(parsed.endTick).to.equal(65535);
    expect(eventsOf(parsed.sequence)).to.deep.equal(independentEvents(clip));
    const own = await encodeMidiClipFile(parsed, fast), roundtrip = new JZZ.MIDI.Clip(own.bytes);
    expect(roundtrip.validate()).to.equal(undefined); expect(independentEvents(roundtrip)).to.deep.equal(independentEvents(clip));
    const sharing = wire([0x00400000, 0x003003c0, 0x00400000, 0xf0200000, 0, 0, 0, 0x00400001, ...on, ...off, 0x00400003, 0xf0210000, 0, 0, 0]);
    expect(eventsOf((await decodeMidiClipFile(sharing, fast)).sequence)).to.deep.equal([[1, on], [1, off]]);
  });
  for (const gap of [MIDI_CLIP_MAX_DELTA - 1, MIDI_CLIP_MAX_DELTA, MIDI_CLIP_MAX_DELTA + 1, MIDI_CLIP_MAX_DELTA * 3]) it('qualifies a silent delta of ' + gap + ' through the independent reader', async () => {
    const take = source([[0, on], [gap, off]], { configurationEndTick: gap, endTick: gap * 2 });
    const { bytes, report } = await encodeMidiClipFile(take, fast), independent = new JZZ.MIDI.Clip(bytes);
    expect(independent.validate()).to.equal(undefined); expect(independent.at(-1).tt).to.equal(gap * 2);
    expect(independentEvents(independent).filter(([, words]) => words[0] !== 0)).to.deep.equal([[0, on], [gap, off]]);
    expect(report.fillerNoops).to.equal(gap > MIDI_CLIP_MAX_DELTA ? Math.floor((gap - 1) / MIDI_CLIP_MAX_DELTA) * 3 : 0);
    const parsed = await decodeMidiClipFile(bytes, fast); expect(parsed.configurationEndTick).to.equal(gap); expect(parsed.endTick).to.equal(gap * 2);
    expect((await encodeMidiClipFile(parsed, fast)).bytes).to.deep.equal(bytes);
  });
  it('preserves all reserved message widths and multipart SysEx/Flex as opaque data without dispatch', async () => {
    const events = [[0, [0x31160102, 0x03040506]], [0, [0x31310700, 0]], [0, [0x520301fe, 0xff000000, 0, 0]],
      [0, [0xd1500101, 0x48656c6c, 0x6f20776f, 0x726c6420]], [0, [0xd1d00101, 0x61676169, 0x6e000000, 0]]];
    for (const [type, count] of [[6, 1], [8, 2], [11, 3], [14, 4]]) events.push([0, [type * 0x10000000, ...Array(count - 1).fill(0xfedcba98)]]);
    const encoded = await encodeMidiClipFile(source(events), fast), parsed = await decodeMidiClipFile(encoded.bytes, fast);
    expect(eventsOf(parsed.sequence)).to.deep.equal(events); expect(parsed.report).to.include({ unknownPackets: 4, unknownDisposition: 'preserved-as-data', setupDisposition: 'data-only-never-submitted' });
  });
  it('captures typed columns before yielding and owns returned bytes independently', async () => {
    const events = Array.from({ length: 2048 }, (_, index) => [index, index % 2 ? off : on]), take = source(events);
    let yields = 0;
    const result = await encodeMidiClipFile(take, { yieldControl: async () => { yields++; take.sequence.words.fill(0); take.sequence.ticks.fill(0); } });
    expect(yields).to.be.greaterThan(0); expect(independentEvents(new JZZ.MIDI.Clip(result.bytes))).to.deep.equal(events);
    const bytes = result.bytes.slice(); const parsed = await decodeMidiClipFile(bytes, { yieldControl: async () => { bytes.fill(0); } });
    expect(eventsOf(parsed.sequence)).to.deep.equal(events);
  });
  it('bounds file expansion and admission before large allocation or silent-gap iteration', async () => {
    await rejecting(() => encodeMidiClipFile(source([[Number.MAX_SAFE_INTEGER, on]]), fast), 'output-capacity');
    await rejecting(() => encodeMidiClipFile(source([[MIDI_CLIP_MAX_DELTA + 1, on]]), { ...fast, maximumEvents: 1 }), 'event-capacity');
    await rejecting(() => encodeMidiClipFile(source([[0, on]]), { ...fast, maxBytes: 56 }), 'output-capacity');
    await rejecting(() => encodeMidiClipFile(source(), { ...fast, estimatedPeakBytes: 4096 }), 'memory-capacity');
    await rejecting(() => decodeMidiClipFile(wire([0x00400000, 0x003003c0, 0x00400000, 0xf0200000, 0, 0, 0, 0x00400000, ...on, 0x00400000, 0xf0210000, 0, 0, 0]), { ...fast, maximumEvents: 0 }), 'event-capacity');
  });
  it('settles cancellation before and during encode/decode without publishing partial output', async () => {
    const take = source(Array.from({ length: 2048 }, (_, index) => [index, on])); const abort = new AbortController(); abort.abort();
    await rejecting(() => encodeMidiClipFile(take, { ...fast, signal: abort.signal }), 'canceled');
    await rejecting(() => encodeMidiClipFile(take, { current: () => false }), 'canceled');
    let current = true; await rejecting(() => encodeMidiClipFile(take, { current: () => current, yieldControl: async () => { current = false; } }), 'canceled');
    const { bytes } = await encodeMidiClipFile(take, fast); current = true;
    await rejecting(() => decodeMidiClipFile(bytes, { current: () => current, yieldControl: async () => { current = false; } }), 'canceled');
  });
  it('rejects bad timeline, offsets, mutable shared storage, injected structure and header order', async () => {
    for (const ppq of [0, 65536, NaN, 1.5]) await rejecting(() => encodeMidiClipFile(source([], { ppq }), fast), 'invalid-timeline');
    for (const events of [[[1, on], [0, off]], [[NaN, on]], [[-1, on]], [[0.5, on]]]) await rejecting(() => encodeMidiClipFile(source(events, { endTick: 10 }), fast), 'invalid-timeline');
    await rejecting(() => encodeMidiClipFile(source([[10, on]], { endTick: 9 }), fast), 'invalid-timeline');
    await rejecting(() => encodeMidiClipFile(source([], { configuration: clipColumns([[10, on]]), configurationEndTick: 9 }), fast), 'invalid-timeline');
    for (const words of [[0x00400000], [0x00300001], [0xf0200000, 0, 0, 0], [0xf0210000, 0, 0, 0]]) await rejecting(() => encodeMidiClipFile(source([[0, words]]), fast), 'owned-structure');
    for (const configuration of [[[1, tempo]], [[0, meter]], [[0, on], [0, tempo]], [[0, tempo], [0, tempo]], [[0, tempo], [0, meter], [0, meter]]]) await rejecting(() => encodeMidiClipFile(source([], { configuration: clipColumns(configuration), configurationEndTick: 10 }), fast), 'configuration-order');
    const invalid = source([[0, on]]); invalid.sequence.offsets[1] = 1; await rejecting(() => encodeMidiClipFile(invalid, fast), 'invalid-columns');
    const reversed = source([[0, on], [1, off]]); reversed.sequence.offsets[1] = 0; await rejecting(() => encodeMidiClipFile(reversed, fast), 'packet-length');
    const shared = source([[0, on]]); shared.sequence.words = new Uint32Array(new SharedArrayBuffer(8)); await rejecting(() => encodeMidiClipFile(shared, fast), 'invalid-columns');
    const resizing = source([[0, on]]); resizing.sequence.words = new Uint32Array(new ArrayBuffer(8, { maxByteLength: 16 })); await rejecting(() => encodeMidiClipFile(resizing, fast), 'invalid-columns');
  });
  it('rejects prohibited Property Exchange and timed profiles, unfinished or malformed multipart messages', async () => {
    for (const [words, code] of [[[0x30067e7f, 0x0d30017f], 'property-exchange'], [[0x30067e7f, 0x0d22017f], 'unsupported-profile-preface'],
      [[0x30160102, 0x03040506], 'unfinished-payload'], [[0x30310100, 0], 'payload-order']]) {
      await rejecting(() => encodeMidiClipFile(source([[0, words]]), fast), code);
    }
    const take = source([], { configuration: clipColumns([[0, [0x30160102, 0x03040506]]]) });
    await rejecting(() => encodeMidiClipFile(take, fast), 'unfinished-payload');
  });
  it('rejects every structural truncation and trailing data with bounded explicit errors', async () => {
    const { bytes } = await encodeMidiClipFile(source([[0, on], [960, off]]), fast);
    for (let length = 0; length < bytes.length; length++) {
      let error; try { await decodeMidiClipFile(bytes.subarray(0, length), fast); } catch (caught) { error = caught; } expect(error, 'length ' + length).to.be.an('error');
    }
    const badHeader = bytes.slice(); badHeader[0] = 0; await rejecting(() => decodeMidiClipFile(badHeader, fast), 'file-header');
    const trailing = new Uint8Array(bytes.length + 4); trailing.set(bytes); await rejecting(() => decodeMidiClipFile(trailing, fast), 'clip-marker');
    const consecutive = wire([0x00400000, 0x00400000, 0x003003c0, 0x00400000, 0xf0200000, 0, 0, 0, 0x00400000, 0xf0210000, 0, 0, 0]);
    await rejecting(() => decodeMidiClipFile(consecutive, fast), 'consecutive-clockstamp');
    const zeroPpq = bytes.slice(); new DataView(zeroPpq.buffer).setUint32(12, 0x00300000); await rejecting(() => decodeMidiClipFile(zeroPpq, fast), 'missing-resolution');
    const missingMarkerDelta = wire([0x00400000, 0x003003c0, 0xf0200000, 0, 0, 0, 0x00400000, ...on, 0x00400000, 0xf0210000, 0, 0, 0]);
    await rejecting(() => decodeMidiClipFile(missingMarkerDelta, fast), 'clip-marker');
  });
});
